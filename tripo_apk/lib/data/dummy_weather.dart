  static List<HourlyForecast> _hourly(double base, IconKey icon) {
    final times = ['Now', '1PM', '2PM', '3PM', '4PM', '5PM', '6PM', '7PM'];
    return List.generate(times.length, (i) {
      final t = base - (i * 0.6) + (i.isEven ? 0.4 : -0.3);
      return HourlyForecast(
        time: times[i],
        temp: double.parse(t.toStringAsFixed(1)),
        condition: icon.name,
        icon: icon,
      );
    });
  }

  static List<DailyForecast> _daily(double high, double low, IconKey icon) {
    const days = ['Today', 'Fri', 'Sat', 'Sun', 'Mon', 'Tue', 'Wed'];
    return List.generate(days.length, (i) {
      return DailyForecast(
        day: days[i],
        high: high - i * 0.4,
        low: low - i * 0.2,
        condition: icon.name,
        icon: icon,
        rainChance: (10 + i * 7).clamp(0, 90),
      );
    });
  }
